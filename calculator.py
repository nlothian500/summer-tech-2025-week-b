a = int(input("Please enter your first number"))
b = int(input("Please enter your second number"))
print("please enter in your operation")
op = input()

if(op == "+"):
    print(a+b)
elif(op == "-"):
    print(a-b)
elif(op == "*"):
    print(a*b)
elif(op == "/"):
    print(a/b)

else:
    print("you didnt pick one of the options")












